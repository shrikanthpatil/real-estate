const cataloguePhoneSuffixes = ['43210', '65432', '87654', '21876', '33901'];

function createCatalogueListing(id, data, index) {
  const location = catalogueCities[index % catalogueCities.length];
  const bhk = data.bedrooms || 0;
  const basePrice = data.price || (
    data.category === 'apartment' ? 3200000 + bhk * 2400000 :
    data.category === 'house' ? 6800000 + bhk * 4800000 :
    data.category === 'plot' ? 2800000 + ((index % 5) + 1) * 900000 :
    data.category === 'agriculture' ? 4500000 + ((index % 6) + 1) * 1300000 :
    data.category === 'estate' ? 22000000 + ((index % 5) + 1) * 7500000 :
    data.category === 'commercial' ? 8500000 + ((index % 7) + 1) * 2100000 :
    data.category === 'industrial' ? 12000000 + ((index % 6) + 1) * 2800000 :
    data.category === 'hospitality' ? 18000000 + ((index % 5) + 1) * 9000000 :
    9500000 + ((index % 8) + 1) * 2200000
  );
  const randomPrice = basePrice + ((index * 137000) % 700000);
  const suffix = cataloguePhoneSuffixes[index % cataloguePhoneSuffixes.length];

  return {
    id: String(id),
    type: 'sell',
    category: data.category,
    subcategory: data.subcategory,
    title: data.title,
    price: randomPrice,
    city: location.city,
    state: location.state,
    district: location.district,
    locality: location.locality,
    landmark: data.landmark || `Near ${location.locality}`,
    propertyListingType: data.propertyListingType || (data.category === 'project' ? 'new' : index % 3 === 0 ? 'new' : 'used'),
    area: data.area,
    bedrooms: bhk,
    bathrooms: data.bathrooms,
    furnishing: data.furnishing || 'semi-furnished',
    description: data.description,
    amenities: data.amenities,
    images: data.images || [catalogueImages[index % catalogueImages.length]],
    sellerName: data.sellerName || `Verified ${data.category === 'project' ? 'Builder' : 'Property'} Seller ${index + 1}`,
    sellerPhone: data.sellerPhone || `+91 98${index % 10}${index % 7}${index % 9}0 ${suffix}`,
    sellerEmail: data.sellerEmail || `seller${index + 1}@openestate.example`,
    postedAt: new Date(`2026-11-${String(24 - (index % 24)).padStart(2, '0')}`).toISOString(),
    featured: index % 7 === 0,
  };
}

